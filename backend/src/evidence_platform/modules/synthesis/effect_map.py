"""Quantitative Evidence Map: effect-size extraction + heterogeneity screening.

1. ``extract_effects`` pulls ratio estimates (HR / OR / RR and sub-hazard ratios)
   with their 95% confidence intervals and p-values out of retrieved passages
   using deterministic patterns. Every estimate keeps the exact source span it
   came from, so it can be audited; nothing is generated by the LLM.
2. ``build_evidence_map`` groups estimates by (measure, endpoint), keeps one
   estimate per paper, and computes inverse-variance statistics on the log
   scale: Cochran's Q, I^2, tau^2 (DerSimonian-Laird) and an exploratory
   random-effects pooled estimate (only when >= 3 papers report the same
   measure for the same endpoint).

The pooled value is a *screening signal*, explicitly not a meta-analysis:
the studies were not selected systematically and may differ in population,
comparator and follow-up. Its main use is to detect quantitative conflict
(high I^2 or significant effects in opposite directions).
"""
from __future__ import annotations

import math
import re
from dataclasses import dataclass, asdict, field
from typing import Any

Z95 = 1.959963984540054

# Normalise Lancet-style mid-dot decimals and unicode dashes; collapse "95% CI"
# variants into the token "CI" so the numbers that follow are unambiguous.
_CI_TOKEN = re.compile(r"95\s*%\s*(?:CI|C\.I\.|confidence intervals?)s?", re.I)
_NUM = r"\d{1,3}(?:\.\d{1,4})?"
_MEASURE = (
    r"(?P<measure>sub-?distribution hazard ratio|sub-?hazard ratio|hazard ratio|odds ratio|risk ratio|relative risk"
    r"|(?-i:\baHR\b|\baOR\b|\bsHR\b|\bHR\b|\bOR\b|\bRR\b))"
)
_EFFECT_RE = re.compile(
    _MEASURE
    + r"(?:\s*\((?:a?HR|a?OR|RR)s?\)\s*)?"          # "odds ratio (OR)"
    + r"(?P<pre>[^\d\n|]{0,24}?)"                     # ", ", " = ", " [CI]: ", " was "
    + r"(?P<est>" + _NUM + r")(?!\s*%)(?!\d)"
    + r"(?P<mid>[^\d\n|]{0,22}?)"                     # " (CI ", "; CI, ", " ["
    + r"(?P<lo>" + _NUM + r")(?!\s*%)"
    + r"\s*(?:–|-|—|to|,|;)\s*"
    + r"(?P<hi>" + _NUM + r")(?!\s*%)(?!\d)",
    re.I,
)
_P_RE = re.compile(r"\bp\s*(?:-?value)?\s*(?P<op>[<=>≤≥])\s*(?P<p>0?\.\d+|1(?:\.0+)?)", re.I)

ENDPOINTS: list[tuple[str, str]] = [
    (r"\boverall survival\b|\bOS\b|overall mortality|all-cause mortality|death from any cause", "Overall survival"),
    (r"progression[- ]free survival|\bPFS\b", "Progression-free survival"),
    (r"disease[- ]free survival|\bDFS\b|invasive disease[- ]free", "Disease-free survival"),
    (r"event[- ]free survival|\bEFS\b", "Event-free survival"),
    (r"recurrence[- ]free survival|\bRFS\b|relapse[- ]free", "Recurrence-free survival"),
    (r"pathologic(?:al)? complete response|\bpCR\b", "Pathological complete response"),
    (r"objective response|overall response|\bORR\b|response rate", "Objective response"),
    (r"\brecurrence\b|\brelapse\b", "Recurrence"),
    (r"cancer[- ]specific (?:mortality|survival)|breast cancer mortality", "Cancer-specific mortality"),
    (r"adverse event|toxicit|grade\s*[≥>]?\s*3", "Adverse events"),
    (r"\bmortality\b|\bdeath\b", "Mortality"),
]
_ENDPOINT_RES = [(re.compile(p, re.I), name) for p, name in ENDPOINTS]


_TREATMENT_CTX = re.compile(
    r"\bvs\.?\b|\bversus\b|compared (?:with|to)|\bplacebo\b|\barm\b|randomi[sz]ed to|\bcontrol group\b"
    r"|plus\b|\bcombination\b|treated with|receiving|\bchemotherapy\b|\bmonotherapy\b|favou?ring|\btreatment\b"
    r"|\bpooled\b|\bintervention\b|\btherapy\b",
    re.I,
)
_PROGNOSTIC_CTX = re.compile(
    r"associated with|association|risk factor|predictor|predictive of|prognostic|multivariat|univariat"
    r"|independent(?:ly)?\b|expression|\bhigh(?:er)? levels?\b|\bmutation status\b|\bper (?:unit|1)\b|\bscore\b"
    r"|\bnomogram\b|\bratio of\b|\bage\b|\bsmok",
    re.I,
)


def _classify_context(text: str, start: int, end: int) -> str:
    """Treatment comparison vs prognostic/association estimate, from nearby wording."""
    window = text[max(0, start - 200):min(len(text), end + 60)]
    t = len(_TREATMENT_CTX.findall(window))
    p = len(_PROGNOSTIC_CTX.findall(window))
    if p > t:
        return "prognostic_association"
    if t > 0:
        return "treatment_comparison"
    return "unclear"


def _measure_family(raw: str) -> str:
    r = raw.lower()
    if "hazard" in r or r.endswith("hr"):
        return "HR"
    if "odds" in r or r.endswith("or"):
        return "OR"
    return "RR"


def _endpoint_near(text: str, pos: int) -> str | None:
    """Nearest endpoint mention in the 160 characters before the estimate."""
    window = text[max(0, pos - 160):pos]
    best, best_key = None, (-1, -1)
    for rx, name in _ENDPOINT_RES:
        for m in rx.finditer(window):
            # nearest mention wins; for overlapping mentions ("overall mortality"
            # vs "mortality") the longer, more specific term wins
            key = (m.end(), m.end() - m.start())
            if key > best_key:
                best, best_key = name, key
    return best


@dataclass
class EffectEstimate:
    measure: str                 # HR | OR | RR
    estimate: float
    ci_low: float
    ci_high: float
    endpoint: str | None
    p_value: str | None
    quote: str                   # exact source text of the estimate
    span_start: int              # char offsets within the chunk text
    span_end: int
    chunk_id: str = ""
    pmcid: str = ""
    title: str = ""
    year: str | None = None
    study_type: str = ""
    evidence_id: str | None = None  # E01.. if the chunk was given to the generator
    context: str = "unclear"         # treatment_comparison | prognostic_association | unclear

    @property
    def significant(self) -> bool:
        return self.ci_high < 1.0 or self.ci_low > 1.0

    @property
    def direction(self) -> str:
        if self.ci_high < 1.0:
            return "favours_lower"   # e.g. HR < 1: fewer events in the intervention arm
        if self.ci_low > 1.0:
            return "favours_higher"
        return "inconclusive"

    def to_dict(self) -> dict[str, Any]:
        d = asdict(self)
        d.update(significant=self.significant, direction=self.direction)
        return d


def extract_effects(text: str) -> list[EffectEstimate]:
    """Deterministically extract ratio estimates with 95% CIs from one passage."""
    if not text:
        return []
    norm = text.replace("·", ".").replace(" ", " ").replace(" ", " ")
    norm = _CI_TOKEN.sub(lambda m: "CI" + " " * (len(m.group(0)) - 2), norm)  # keep offsets stable
    out: list[EffectEstimate] = []
    for m in _EFFECT_RE.finditer(norm):
        between = (m.group("pre") or "") + (m.group("mid") or "")
        if "CI" not in between and "[" not in m.group("mid") and "(" not in m.group("mid"):
            continue  # numbers not presented as an estimate + interval
        try:
            est, lo, hi = float(m.group("est")), float(m.group("lo")), float(m.group("hi"))
        except ValueError:
            continue
        if not (0 < lo <= est <= hi) or hi > 100 or est == 0:
            continue
        if hi / lo > 400:  # implausible / mis-parsed interval
            continue
        tail = norm[m.end(): m.end() + 40]
        pm = _P_RE.search(tail)
        p_value = f"{pm.group('op')}{pm.group('p')}" if pm else None
        end = m.end() + (pm.end() if pm else 0)
        out.append(EffectEstimate(
            measure=_measure_family(m.group("measure")),
            estimate=est, ci_low=lo, ci_high=hi,
            endpoint=_endpoint_near(norm, m.start()),
            p_value=p_value,
            quote=text[m.start():end].strip(),
            span_start=m.start(), span_end=end,
            context=_classify_context(norm, m.start(), end),
        ))
    return out


@dataclass
class EffectGroup:
    measure: str
    endpoint: str
    context: str = "treatment_comparison"
    estimates: list[EffectEstimate] = field(default_factory=list)
    k: int = 0
    q: float | None = None
    i2: float | None = None
    tau2: float | None = None
    pooled: dict[str, float] | None = None
    direction_agreement: float | None = None
    conflict: str | None = None

    def to_dict(self) -> dict[str, Any]:
        return {
            "measure": self.measure, "endpoint": self.endpoint, "context": self.context, "k": self.k,
            "q": self.q, "i2": self.i2, "tau2": self.tau2, "pooled": self.pooled,
            "direction_agreement": self.direction_agreement, "conflict": self.conflict,
            "estimates": [e.to_dict() for e in self.estimates],
        }


def _log_se(e: EffectEstimate) -> float:
    return (math.log(e.ci_high) - math.log(e.ci_low)) / (2 * Z95)


def heterogeneity(estimates: list[EffectEstimate]) -> dict[str, Any]:
    """Inverse-variance Q, I^2, DerSimonian-Laird tau^2 and random-effects pooled ratio."""
    ys, ws = [], []
    for e in estimates:
        se = _log_se(e)
        if se <= 0:
            continue
        ys.append(math.log(e.estimate))
        ws.append(1.0 / se ** 2)
    k = len(ys)
    if k < 2:
        return {"k": k, "q": None, "i2": None, "tau2": None, "pooled": None}
    sw = sum(ws)
    y_fixed = sum(w * y for w, y in zip(ws, ys)) / sw
    q = sum(w * (y - y_fixed) ** 2 for w, y in zip(ws, ys))
    df = k - 1
    i2 = max(0.0, (q - df) / q) if q > 0 else 0.0
    c = sw - sum(w * w for w in ws) / sw
    tau2 = max(0.0, (q - df) / c) if c > 0 else 0.0
    w_re = [1.0 / (1.0 / w + tau2) for w in ws]
    y_re = sum(w * y for w, y in zip(w_re, ys)) / sum(w_re)
    se_re = math.sqrt(1.0 / sum(w_re))
    pooled = None
    if k >= 3:
        pooled = {
            "estimate": round(math.exp(y_re), 3),
            "ci_low": round(math.exp(y_re - Z95 * se_re), 3),
            "ci_high": round(math.exp(y_re + Z95 * se_re), 3),
            "label": "Exploratory random-effects estimate (screening only, not a meta-analysis)",
        }
    return {"k": k, "q": round(q, 3), "i2": round(i2 * 100, 1), "tau2": round(tau2, 4), "pooled": pooled}


def build_evidence_map(candidates: list[Any], evidence_ids: dict[str, str] | None = None,
                       max_groups: int = 4) -> dict[str, Any]:
    """Extract estimates from candidate passages and build per-endpoint groups.

    ``evidence_ids`` maps chunk_id -> "E01" for passages given to the generator.
    One estimate per paper per group (the first one in rank order) so a single
    paper cannot dominate or "disagree with itself".
    """
    evidence_ids = evidence_ids or {}
    all_est: list[EffectEstimate] = []
    for c in candidates:
        for e in extract_effects(getattr(c, "text", "")):
            e.chunk_id = getattr(c, "chunk_id", "")
            e.pmcid = getattr(c, "pmcid", "") or ""
            e.title = getattr(c, "title", "") or ""
            e.year = (getattr(c, "publication_date", "") or "")[:4] or None
            e.study_type = getattr(c, "study_type", "") or ""
            e.evidence_id = evidence_ids.get(e.chunk_id)
            all_est.append(e)

    groups: dict[tuple[str, str], EffectGroup] = {}
    for e in all_est:
        if not e.endpoint:
            continue
        # Treatment-effect and prognostic-association estimates are never pooled
        # or compared with each other (a prognostic HR of 2.7 does not contradict
        # a treatment HR of 0.6).
        ctx = "prognostic_association" if e.context == "prognostic_association" else "treatment_comparison"
        key = (e.measure, e.endpoint, ctx)
        g = groups.setdefault(key, EffectGroup(measure=e.measure, endpoint=e.endpoint, context=ctx))
        if any(x.pmcid == e.pmcid and e.pmcid for x in g.estimates):
            continue
        g.estimates.append(e)

    out_groups: list[EffectGroup] = []
    for g in groups.values():
        stats = heterogeneity(g.estimates)
        g.k, g.q, g.i2, g.tau2, g.pooled = stats["k"] or len(g.estimates), stats["q"], stats["i2"], stats["tau2"], stats["pooled"]
        dirs = [e.direction for e in g.estimates if e.direction != "inconclusive"]
        if dirs:
            top = max(set(dirs), key=dirs.count)
            g.direction_agreement = round(dirs.count(top) / len(dirs), 2)
        if g.context != "treatment_comparison":
            pass  # prognostic associations are displayed but not treated as conflicts
        elif "favours_lower" in dirs and "favours_higher" in dirs:
            g.conflict = "Statistically significant effects in OPPOSITE directions across papers"
        elif g.i2 is not None and g.k >= 3 and g.i2 >= 50:
            g.conflict = f"Substantial statistical heterogeneity (I² = {g.i2:.0f}%)"
        out_groups.append(g)

    out_groups.sort(key=lambda g: (g.context != "treatment_comparison", -len(g.estimates), g.endpoint))
    shown = out_groups[:max_groups]
    return {
        "n_estimates": len(all_est),
        "n_papers": len({e.pmcid for e in all_est if e.pmcid}),
        "groups": [g.to_dict() for g in shown],
        "quantitative_conflicts": [
            {"measure": g.measure, "endpoint": g.endpoint, "context": g.context, "k": g.k, "i2": g.i2, "description": g.conflict}
            for g in out_groups if g.conflict
        ],
        "note": "Estimates are extracted verbatim from retrieved passages. Pooled values are exploratory heterogeneity "
                "screening, not a systematic meta-analysis.",
    }
